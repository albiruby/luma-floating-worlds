const WORLD_MAP = new Map<WorldId, WorldDefinition>(WORLDS.map((w) => [w.id, w]));

export function getWorldById(id: WorldId | undefined): WorldDefinition {
  if (id && WORLD_MAP.has(id)) {
    return WORLD_MAP.get(id)!;
  }
  return WORLDS[0];
}

export function getWorldForLevelId(levelId: number): WorldDefinition {
  for (const w of WORLDS) {
    if (levelId >= w.levelRange[0] && levelId <= w.levelRange[1]) {
      return w;
    }
  }
  return WORLDS[0];
}
